def state_name(address: str) -> str:
    if address in KNOWN_STATE:
        return KNOWN_STATE[address]
    space, raw = address.split(":")
    value = int(raw, 16)
    if space == "SFR" and value in SFR_NAMES:
        return SFR_NAMES[value]
    return f"unknown_{space.lower()}_{value:04x}"
